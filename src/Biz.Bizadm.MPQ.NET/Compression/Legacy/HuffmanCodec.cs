/// <summary>
/// MPQ Huffman compression (mask 0x01), byte-compatible with StormLib's THuffmannTree.
/// </summary>
internal static class HuffmanCodec
{
    private const uint DataTypeSparse = 0x00;

    private const int LinkItemCount = 128;      // Maximum number of quick-link items
    private const int ByteItemCount = 258;      // Number of items-by-byte
    private const int HuffItemCount = 515;      // Number of items in the item pool
    private const int DataTypeCount = 9;        // Number of weight tables

    private const uint HuffDecompressError = 0x1FF;

    /// <summary>
    /// Decompresses a Huffman stream into <paramref name="output"/>, whose length is the
    /// expected (maximum) decompressed size. Returns the number of bytes written.
    /// </summary>
    /// <exception cref="InvalidDataException">The stream is malformed, or StormLib would report failure (zero bytes).</exception>
    public static int Decompress(ReadOnlySpan<byte> input, Span<byte> output)
    {
        var tree = new HuffmanTree();
        var stream = new InputStream(input);

        int written = (int)tree.Decompress(output, ref stream);
        if (written == 0)
            throw new InvalidDataException("Huffman decompression failed.");

        return written;
    }

    /// <summary>
    /// Compresses <paramref name="input"/> with the weight table selected by
    /// <paramref name="compressionType"/> (StormLib's nCmpType: 0 for plain Huffman,
    /// 6, 7 or 8 after ADPCM). The result does not include the MPQ compression mask byte.
    /// </summary>
    public static byte[] Compress(ReadOnlySpan<byte> input, int compressionType)
    {
        if ((compressionType & 0x0F) >= DataTypeCount)
            throw new ArgumentOutOfRangeException(nameof(compressionType), compressionType, "Unsupported Huffman data type.");

        var tree = new HuffmanTree();
        var stream = new OutputStream(input.Length + 16);

        tree.Compress(stream, input, compressionType);
        return stream.ToArray();
    }

    //-------------------------------------------------------------------------
    // Bit streams

    // Input stream for Huffman decompression (TInputStream)
    private ref struct InputStream
    {
        private readonly ReadOnlySpan<byte> buffer;
        private int position;
        private uint bitBuffer;     // Input bit buffer
        private uint bitCount;      // Number of bits remaining in 'bitBuffer'

        public InputStream(ReadOnlySpan<byte> buffer)
        {
            this.buffer = buffer;
        }

        // Gets one bit from input stream
        public bool Get1Bit(out uint bitValue)
        {
            bitValue = 0;

            // Ensure that the input stream is reloaded, if there are no bits left
            if (bitCount == 0)
            {
                if (position >= buffer.Length)
                    return false;

                bitBuffer = buffer[position++];
                bitCount = 8;
            }

            bitValue = bitBuffer & 0x01;
            bitBuffer >>= 1;
            bitCount--;
            return true;
        }

        // Gets the whole byte from the input stream
        public bool Get8Bits(out uint byteValue)
        {
            byteValue = 0;

            if (bitCount < 8)
            {
                if (position >= buffer.Length)
                    return false;

                bitBuffer |= (uint)buffer[position++] << (int)bitCount;
                bitCount += 8;
            }

            byteValue = bitBuffer & 0xFF;
            bitBuffer >>= 8;
            bitCount -= 8;
            return true;
        }

        // Gets 7 bits from the stream. Does NOT remove the bits from the input stream
        public bool Peek7Bits(out uint value)
        {
            value = 0;

            if (bitCount < 7)
            {
                if (position >= buffer.Length)
                    return false;

                bitBuffer |= (uint)buffer[position++] << (int)bitCount;
                bitCount += 8;
            }

            value = bitBuffer & 0x7F;
            return true;
        }

        public void SkipBits(uint bitsToSkip)
        {
            if (bitCount < bitsToSkip)
            {
                if (position >= buffer.Length)
                    return;

                bitBuffer |= (uint)buffer[position++] << (int)bitCount;
                bitCount += 8;
            }

            bitBuffer >>= (int)bitsToSkip;
            bitCount -= bitsToSkip;
        }
    }

    // Output stream for Huffman compression (TOutputStream). Grows instead of
    // truncating, which equals StormLib's output for a large enough buffer.
    private sealed class OutputStream
    {
        private byte[] buffer;
        private int length;
        private uint bitBuffer;     // Bit buffer
        private uint bitCount;      // Number of bits in the bit buffer

        public OutputStream(int initialCapacity)
        {
            buffer = new byte[Math.Max(initialCapacity, 16)];
        }

        public void PutBits(uint value, uint count)
        {
            bitBuffer |= value << (int)bitCount;
            bitCount += count;

            // Flush completed bytes
            while (bitCount >= 8)
            {
                WriteByte((byte)bitBuffer);
                bitBuffer >>= 8;
                bitCount -= 8;
            }
        }

        public void Flush()
        {
            while (bitCount != 0)
            {
                WriteByte((byte)bitBuffer);
                bitBuffer >>= 8;
                bitCount -= (bitCount > 8) ? 8 : bitCount;
            }
        }

        public byte[] ToArray() => buffer.AsSpan(0, length).ToArray();

        private void WriteByte(byte value)
        {
            if (length == buffer.Length)
                Array.Resize(ref buffer, buffer.Length * 2);

            buffer[length++] = value;
        }
    }

    //-------------------------------------------------------------------------
    // Huffman tree

    private enum InsertPoint
    {
        After = 1,
        Before = 2,
    }

    // Huffman tree item (THTreeItem)
    private sealed class TreeItem
    {
        public TreeItem? Next;              // Lower-weight tree item
        public TreeItem? Prev;              // Higher-weight tree item
        public uint DecompressedValue;      // Decompressed byte value (also index in ItemsByByte)
        public uint Weight;
        public TreeItem? Parent;            // Parent item (null if none)
        public TreeItem? ChildLo;           // Lower-weight child ("left child")

        public void RemoveItem()
        {
            if (Next != null)
            {
                Prev!.Next = Next;
                Next.Prev = Prev;
                Next = Prev = null;
            }
        }
    }

    // Quick navigation in the tree (TQuickLink). The C union of pItem and
    // DecompressedValue is kept as two fields; only one is used per ValidBits.
    private struct QuickLink
    {
        public uint ValidValue;             // Valid if greater than MinValidValue
        public uint ValidBits;              // Number of bits that are valid for this item link
        public TreeItem? Item;              // Tree item, when ValidBits > 7
        public uint DecompressedValue;      // Decompressed value, when ValidBits <= 7
    }

    // Adaptive Huffman tree (THuffmannTree)
    private sealed class HuffmanTree
    {
        private readonly TreeItem[] itemBuffer = new TreeItem[HuffItemCount];
        private int itemsUsed;

        // Sentinel of the circular weight-sorted list.
        // ListHead.Next = highest weight item, ListHead.Prev = lowest weight item.
        private readonly TreeItem listHead = new();

        private readonly TreeItem?[] itemsByByte = new TreeItem?[ByteItemCount];
        private readonly QuickLink[] quickLinks = new QuickLink[LinkItemCount];

        private uint minValidValue = 1;
        private bool isSparseData;

        // StormLib zeroes the quick links only for decompression; compression never reads them.
        public HuffmanTree()
        {
            listHead.Next = listHead.Prev = listHead;
            for (int i = 0; i < itemBuffer.Length; i++)
                itemBuffer[i] = new TreeItem();
        }

        private static void LinkTwoItems(TreeItem item1, TreeItem item2)
        {
            item2.Next = item1.Next;
            item2.Prev = item1.Next!.Prev;
            item1.Next.Prev = item2;
            item1.Next = item2;
        }

        // Inserts item into the weight-sorted linked list
        private void InsertItem(TreeItem newItem, InsertPoint insertPoint, TreeItem? insertAt)
        {
            newItem.RemoveItem();

            insertAt ??= listHead;

            switch (insertPoint)
            {
                case InsertPoint.After:
                    LinkTwoItems(insertAt, newItem);
                    return;

                case InsertPoint.Before:
                    LinkTwoItems(insertAt.Prev!, newItem);
                    return;
            }
        }

        private TreeItem FindHigherOrEqualItem(TreeItem? item, uint weight)
        {
            if (item != null)
            {
                while (item != listHead)
                {
                    if (item!.Weight >= weight)
                        return item;

                    item = item.Prev;
                }
            }

            // If not found, we just get the list head
            return listHead;
        }

        private TreeItem? CreateNewItem(uint decompressedValue, uint weight, InsertPoint insertPoint)
        {
            // Don't let the item buffer run out of space
            if (itemsUsed >= HuffItemCount)
                return null;

            var newItem = itemBuffer[itemsUsed++];
            InsertItem(newItem, insertPoint, null);

            newItem.DecompressedValue = decompressedValue;
            newItem.Weight = weight;
            newItem.Parent = null;
            newItem.ChildLo = null;
            return newItem;
        }

        private uint FixupItemPosByWeight(TreeItem newItem, uint maxWeight)
        {
            if (newItem.Weight < maxWeight)
            {
                // Find an item that has higher weight than this one
                var higherItem = FindHigherOrEqualItem(listHead.Prev, newItem.Weight);

                // Remove the item and put it to the new position
                newItem.RemoveItem();
                LinkTwoItems(higherItem, newItem);
            }
            else
            {
                maxWeight = newItem.Weight;
            }

            return maxWeight;
        }

        // Builds the Huffman tree from the pre-initialized weight table for the data type
        private bool BuildTree(uint dataType)
        {
            Array.Clear(itemsByByte);
            uint maxWeight = 0;

            dataType &= 0x0F;
            if (dataType >= DataTypeCount)
                return false;
            ReadOnlySpan<byte> distTable = GetDataDistribution(dataType);

            // Build the linear list of entries that is sorted by byte weight
            for (uint i = 0; i < 0x100; i++)
            {
                if (distTable[(int)i] != 0)
                {
                    var newItem = CreateNewItem(i, distTable[(int)i], InsertPoint.After)!;
                    itemsByByte[i] = newItem;
                    maxWeight = FixupItemPosByWeight(newItem, maxWeight);
                }
            }

            // Insert termination entries at the end of the list
            itemsByByte[0x100] = CreateNewItem(0x100, 1, InsertPoint.Before);
            itemsByByte[0x101] = CreateNewItem(0x101, 1, InsertPoint.Before);

            // Build the tree, starting at the last entry and going backwards
            var childLo = listHead.Prev!;
            while (childLo != listHead)
            {
                var childHi = childLo.Prev!;
                if (childHi == listHead)
                    break;

                var newItem = CreateNewItem(0, childHi.Weight + childLo.Weight, InsertPoint.After);
                if (newItem == null)
                    return false;

                childLo.Parent = newItem;
                childHi.Parent = newItem;
                newItem.ChildLo = childLo;

                maxWeight = FixupItemPosByWeight(newItem, maxWeight);

                childLo = childHi.Prev!;
            }

            // Invalidate all quick-link items
            minValidValue = 1;
            return true;
        }

        private void IncWeightsAndRebalance(TreeItem? item)
        {
            // Climb up the tree and increment weight of each tree item
            for (; item != null; item = item.Parent)
            {
                item.Weight++;

                // Find a previous item with equal or greater weight, which is not equal to this item
                var higherItem = FindHigherOrEqualItem(item.Prev, item.Weight);
                var childHi = higherItem.Next!;

                if (childHi != item)
                {
                    // StormLib would dereference a null parent here; only a corrupt tree gets this far
                    if (childHi.Parent == null || item.Parent == null)
                        throw new InvalidDataException("Huffman tree is corrupt.");

                    // Move the previous item to the RIGHT from the given item
                    childHi.RemoveItem();
                    LinkTwoItems(item, childHi);

                    // Move the given item AFTER the greater-weight tree item
                    item.RemoveItem();
                    LinkTwoItems(higherItem, item);

                    // Keep childHi.Weight >= childLo.Weight by swapping the two subtrees
                    var childLo = childHi.Parent.ChildLo;
                    var parent = item.Parent;
                    if (parent.ChildLo == item)
                        parent.ChildLo = childHi;
                    if (childLo == childHi)
                        childHi.Parent.ChildLo = item;
                    parent = item.Parent;
                    item.Parent = childHi.Parent;
                    childHi.Parent = parent;

                    // Invalidate all quick-link items
                    minValidValue++;
                }
            }
        }

        private bool InsertNewBranchAndRebalance(uint value1, uint value2)
        {
            var lastItem = listHead.Prev!;

            // Create higher-weight child
            var childHi = CreateNewItem(value1, lastItem.Weight, InsertPoint.Before);
            if (childHi != null)
            {
                childHi.Parent = lastItem;
                itemsByByte[value1] = childHi;

                // Create lower-weight child
                var childLo = CreateNewItem(value2, 0, InsertPoint.Before);
                if (childLo != null)
                {
                    childLo.Parent = lastItem;
                    lastItem.ChildLo = childLo;
                    itemsByByte[value2] = childLo;

                    IncWeightsAndRebalance(childLo);
                    return true;
                }
            }

            // No more space in the tree buffer
            return false;
        }

        private static void EncodeOneByte(OutputStream os, TreeItem item)
        {
            var parent = item.Parent;
            uint bitBuffer = 0;
            uint bitCount = 0;

            // Walk from leaf to root, collecting 0/1 bits based on child position
            while (parent != null)
            {
                bitBuffer = (bitBuffer << 1) | ((parent.ChildLo != item) ? 1u : 0u);
                bitCount++;

                item = parent;
                parent = parent.Parent;
            }

            os.PutBits(bitBuffer, bitCount);
        }

        private uint DecodeOneByte(ref InputStream input)
        {
            TreeItem? itemLink = null;
            TreeItem item;
            uint bitCount = 0;

            // Try to retrieve quick link index
            bool hasItemLinkIndex = input.Peek7Bits(out uint itemLinkIndex);

            if (hasItemLinkIndex && quickLinks[itemLinkIndex].ValidValue > minValidValue)
            {
                // If that item needs less than 7 bits, we can get decompressed value directly
                if (quickLinks[itemLinkIndex].ValidBits <= 7)
                {
                    input.SkipBits(quickLinks[itemLinkIndex].ValidBits);
                    return quickLinks[itemLinkIndex].DecompressedValue;
                }

                // Otherwise we can skip 7 levels of tree parsing
                item = quickLinks[itemLinkIndex].Item!;
                input.SkipBits(7);
            }
            else
            {
                if (listHead.Next == listHead)
                    return HuffDecompressError;

                // Parse the tree from its root
                item = listHead.Next!;
            }

            // Step down the tree until we find a terminal item
            while (item.ChildLo != null)
            {
                if (!input.Get1Bit(out uint bitValue))
                    return HuffDecompressError;

                // Set bit selects the higher-weight child, clear bit the lower-weight child
                item = bitValue != 0 ? item.ChildLo.Prev! : item.ChildLo;
                bitCount++;

                // Remember the item reached after 7 bits for the quick-link array
                if (bitCount == 7)
                    itemLink = item;
            }

            // If we didn't get the item from the quick-link array, set the entry in it
            if (hasItemLinkIndex && quickLinks[itemLinkIndex].ValidValue < minValidValue)
            {
                if (bitCount > 7)
                {
                    quickLinks[itemLinkIndex].ValidValue = minValidValue;
                    quickLinks[itemLinkIndex].ValidBits = bitCount;
                    quickLinks[itemLinkIndex].Item = itemLink;
                }
                else
                {
                    // Limit the quick-decompress item to lower amount of bits
                    itemLinkIndex = (bitCount != 0) ? itemLinkIndex & (0xFFFFFFFF >> (int)(32 - bitCount)) : 0;
                    while (itemLinkIndex < LinkItemCount)
                    {
                        quickLinks[itemLinkIndex].ValidValue = minValidValue;
                        quickLinks[itemLinkIndex].ValidBits = bitCount;
                        quickLinks[itemLinkIndex].DecompressedValue = item.DecompressedValue;

                        itemLinkIndex += 1u << (int)bitCount;
                    }
                }
            }

            return item.DecompressedValue;
        }

        public void Compress(OutputStream os, ReadOnlySpan<byte> input, int dataType)
        {
            if (!BuildTree((uint)dataType))
                throw new ArgumentOutOfRangeException(nameof(dataType));
            isSparseData = (uint)dataType == DataTypeSparse;

            // Store the compression type into output buffer
            os.PutBits((uint)dataType, 8);

            foreach (byte inputByte in input)
            {
                if (itemsByByte[inputByte] == null)
                {
                    // Encode the NYT (Not Yet Transmitted) escape symbol, then the literal byte
                    EncodeOneByte(os, itemsByByte[0x101]!);
                    os.PutBits(inputByte, 8);

                    if (!InsertNewBranchAndRebalance(listHead.Prev!.DecompressedValue, inputByte))
                        throw new InvalidOperationException("Huffman item pool exhausted.");

                    IncWeightsAndRebalance(itemsByByte[inputByte]);
                    if (isSparseData)
                        continue;
                }
                else
                {
                    EncodeOneByte(os, itemsByByte[inputByte]!);
                }

                if (isSparseData)
                    IncWeightsAndRebalance(itemsByByte[inputByte]);
            }

            // Put the termination mark to the compressed stream
            EncodeOneByte(os, itemsByByte[0x100]!);
            os.Flush();
        }

        public uint Decompress(Span<byte> output, ref InputStream input)
        {
            int outPos = 0;
            uint decompressedValue;

            if (output.Length == 0)
                return 0;

            // Get the compression type from the input stream
            if (!input.Get8Bits(out uint dataType))
                return 0;
            isSparseData = dataType == DataTypeSparse;

            if (!BuildTree(dataType))
                return 0;

            // Process the entire input buffer until end of the stream
            while ((decompressedValue = DecodeOneByte(ref input)) != 0x100)
            {
                if (decompressedValue == HuffDecompressError)
                    return 0;

                // NYT escape: the next 8 bits contain a new, previously unseen byte
                if (decompressedValue == 0x101)
                {
                    if (!input.Get8Bits(out decompressedValue))
                        return 0;

                    if (!InsertNewBranchAndRebalance(listHead.Prev!.DecompressedValue, decompressedValue))
                        return 0;

                    if (!isSparseData)
                        IncWeightsAndRebalance(itemsByByte[decompressedValue]);
                }

                if (outPos >= output.Length)
                    break;
                output[outPos++] = (byte)decompressedValue;

                if (isSparseData)
                    IncWeightsAndRebalance(itemsByByte[decompressedValue]);
            }

            return (uint)outPos;
        }
    }

